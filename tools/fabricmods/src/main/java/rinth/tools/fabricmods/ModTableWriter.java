package rinth.tools.fabricmods;

import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Writes fabric/runtime's {@code FabricModTable}: the mods built in and their entrypoints, made
 * with {@code new}, and what Mod Menu's switches turn on and off without a rebuild
 * ({@link ModSwitchPlan}). The browser build can't find classes by name, so where Fabric Loader
 * would reflect, this table is compiled in.
 */
final class ModTableWriter {

    /** An entrypoint the table makes: {@code sourceName} is its class as Java source names it. */
    record Entry(String key, String modId, String value, String sourceName) {}

    /** The interface each initializer key's entrypoints implement, for a static method given as one. */
    static final Map<String, String> INITIALIZERS = Map.of(
            "main", "net.fabricmc.api.ModInitializer",
            "client", "net.fabricmc.api.ClientModInitializer",
            "server", "net.fabricmc.api.DedicatedServerModInitializer");

    private ModTableWriter() {}

    static String write(
            String minecraft, List<ModJar> mods, List<Entry> entrypoints, ModSwitchPlan plan, Set<String> hidden) {
        StringBuilder out = new StringBuilder();
        out.append("package rinth.fabric.generated;\n\n")
                .append("import java.util.List;\n")
                .append("import java.util.Map;\n")
                .append("import net.fabricmc.loader.impl.FabricLoaderImpl;\n")
                .append("import net.fabricmc.loader.impl.ModContainerImpl;\n")
                .append("import net.fabricmc.loader.impl.ModMetadataImpl;\n\n")
                .append(
                        "/** The Fabric mods built into this client: generated by tools/fabricmods from mods/ (ADR 0065). */\n")
                .append("public final class FabricModTable {\n\n")
                .append("    /** The Minecraft version the mods were built in for. */\n")
                .append("    public static final String MINECRAFT = ")
                .append(literal(minecraft))
                .append(";\n\n")
                .append("    private FabricModTable() {}\n\n")
                .append("    public static List<ModContainerImpl> mods() {\n")
                .append("        return List.of(");
        List<String> items = new ArrayList<>();
        for (ModJar mod : mods) {
            items.add("\n                new ModContainerImpl(new ModMetadataImpl(" + literal(mod.id()) + ", "
                    + literal(mod.version()) + ", " + literal(mod.name()) + ", " + literal(mod.description())
                    + ", " + literal(mod.environment()) + ", " + list(mod.provides()) + ", " + list(mod.authors())
                    + ", " + list(mod.licenses()) + ", " + literal(mod.icon()) + "))");
        }
        out.append(String.join(",", items)).append(");\n    }\n\n");
        out.append("    public static List<FabricLoaderImpl.Entrypoint> entrypoints() {\n")
                .append("        return List.of(");
        items.clear();
        for (Entry entry : entrypoints) {
            String make = entry.sourceName().contains("::")
                    ? "(" + INITIALIZERS.get(entry.key()) + ") " + entry.sourceName()
                    : "new " + entry.sourceName() + "()";
            items.add("\n                new FabricLoaderImpl.Entrypoint(" + literal(entry.key()) + ", "
                    + literal(entry.modId()) + ", " + literal(entry.value()) + ", () -> " + make + ")");
        }
        out.append(String.join(",", items)).append(");\n    }\n\n");
        out.append(
                        "    /** The mods Mod Menu's list leaves out (they still run): libraries, and mods/hidden.txt's. */\n")
                .append("    public static List<String> hidden() {\n        return ")
                .append(list(hidden))
                .append(";\n    }\n\n");
        out.append("    /** The mods Mod Menu switches without a rebuild. */\n")
                .append("    public static List<String> switchable() {\n        return ")
                .append(list(plan.switchable()))
                .append(";\n    }\n\n")
                .append(
                        "    /** The combinations built in, each as the mods it has off; the game runs one by its index. */\n")
                .append("    public static List<List<String>> variants() {\n        return List.of(");
        items.clear();
        for (Set<String> off : plan.variants()) {
            items.add("\n                " + list(off));
        }
        out.append(String.join(",", items)).append(");\n    }\n\n");
        out.append("    /** For each switchable mod, the mods that go off with it, itself included. */\n")
                .append("    public static Map<String, List<String>> dependents() {\n        return ")
                .append(map(plan.dependents()))
                .append(";\n    }\n\n")
                .append(
                        "    /** For each switchable mod, the switchable mods that come on with it, itself included. */\n")
                .append("    public static Map<String, List<String>> requirements() {\n        return ")
                .append(map(plan.requirements()))
                .append(";\n    }\n}\n");
        return out.toString();
    }

    private static String map(Map<String, Set<String>> values) {
        List<String> entries = new ArrayList<>();
        for (Map.Entry<String, Set<String>> entry : values.entrySet()) {
            entries.add("Map.entry(" + literal(entry.getKey()) + ", " + list(entry.getValue()) + ")");
        }
        return "Map.ofEntries(" + String.join(", ", entries) + ")";
    }

    private static String list(Collection<String> values) {
        List<String> literals = new ArrayList<>();
        for (String value : values) {
            literals.add(literal(value));
        }
        return "List.of(" + String.join(", ", literals) + ")";
    }

    /** A Java string literal: quotes, backslashes, control and non-ASCII characters escaped. */
    static String literal(String value) {
        StringBuilder out = new StringBuilder("\"");
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            if (c == '"' || c == '\\') {
                out.append('\\').append(c);
            } else if (c < 0x20 || c > 0x7E) {
                out.append(String.format("\\u%04x", (int) c));
            } else {
                out.append(c);
            }
        }
        return out.append('"').toString();
    }
}
